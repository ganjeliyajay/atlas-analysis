export function getTimeseriesData(range: DateRangeOption = '30d'): TimeseriesPoint[] {
  const pointsCount = range === 'today' ? 12 : range === '7d' ? 7 : range === '90d' ? 14 : 10;

  const baseDates = [
    'Oct 19', 'Oct 20', 'Oct 21', 'Oct 22', 'Oct 23',
    'Oct 24', 'Oct 25', 'Oct 26', 'Oct 27', 'Oct 28',
    'Oct 29', 'Oct 30', 'Oct 31', 'Nov 01'
  ];

  const results: TimeseriesPoint[] = [];

  for (let i = 0; i < pointsCount; i++) {
    const dayLabel = baseDates[i % baseDates.length];
    const wave = Math.sin((i / pointsCount) * Math.PI * 2) * 0.2 + 1;
    const factor = (i + 1) * 0.05 + 0.8;

    results.push({
      date: `2026-10-${(18 + i).toString().padStart(2, '0')}`,
      label: dayLabel,
      activeUsers: Math.round(1450 * wave * factor + (i % 3) * 60),
      eventVolume: Math.round(52000 * wave * factor + (i % 4) * 2100),
      sessions: Math.round(3800 * wave * factor + (i % 2) * 140),
      pageViews: Math.round(28400 * wave * factor + (i % 3) * 800),
    });
  }

  return results;
}

